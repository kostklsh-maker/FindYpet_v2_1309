let currentLang = (function () {
    try { const s = localStorage.getItem("fyp_lang"); if (s && I18N[s]) return s; } catch (e) {}
    const n = (navigator.language || "en").slice(0, 2).toLowerCase();
    return n === "he" || n === "iw" ? "he" : n === "ru" ? "ru" : "en";
})();

function t(key, vars) {
    let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
    if (vars) Object.keys(vars).forEach(function (k) { s = s.split("{" + k + "}").join(vars[k]); });
    return s;
}

// Цены из PRICING (js/plans.js): один жетон, 3 + 1 (4 жетона по цене трёх), «Забота» в месяц
function money(n) {
    const cur = typeof PRICING !== "undefined" ? PRICING.currency : "₪";
    const v = Math.round(n * 100) / 100;               // 147 / 4 = 36.75 — показываем с агорот
    const txt = Number.isInteger(v) ? String(v) : v.toFixed(2);
    return (typeof currentLang !== "undefined" && currentLang === "ru" ? txt.replace(".", ",") : txt) + " " + cur;
}
/** Сколько жетонов в наборе 3 + 1 */
function bundleSize() { return typeof PRICING !== "undefined" && PRICING.bundle ? PRICING.bundle : 4; }
function priceOf(kind) {
    if (typeof PRICING === "undefined") return 0;
    if (kind === "tag") return PRICING.tag;
    if (kind === "two") return PRICING.tag * 2;
    if (kind === "bundle") return PRICING.tag * (bundleSize() - 1);   // 3 + 1: четвёртый в подарок
    if (kind === "care") return PRICING.care;
    return 0;
}
/** Сумма заказа: 1, 2 или 4 (3 + 1) жетона — как normQty/orderPrice в Worker'е */
function orderTotal(qty) {
    if (qty >= bundleSize() - 1) return priceOf("bundle");
    return qty >= 2 ? priceOf("two") : priceOf("tag");
}

const langListeners = [];
function onLang(fn) { langListeners.push(fn); }

function applyLang() {
    const html = document.documentElement;
    html.lang = currentLang;
    html.dir = currentLang === "he" ? "rtl" : "ltr";
    document.title = t("docTitle");
    document.querySelectorAll("[data-t]").forEach(function (el) { el.textContent = t(el.dataset.t); });
    document.querySelectorAll("[data-t-ph]").forEach(function (el) { el.placeholder = t(el.dataset.tPh); });
    document.querySelectorAll(".langs button").forEach(function (b) {
        b.classList.toggle("on", b.dataset.lang === currentLang);
        b.setAttribute("aria-pressed", b.dataset.lang === currentLang ? "true" : "false");
    });
    if (typeof PRICING !== "undefined") {
        document.querySelectorAll("[data-price]").forEach(function (el) {
            const v = priceOf(el.dataset.price); el.textContent = v ? money(v) : "";
        });
        document.querySelectorAll("[data-price-min]").forEach(function (el) { el.textContent = money(PRICING.tag); });
    }
    langListeners.forEach(function (fn) { try { fn(currentLang); } catch (e) { console.error(e); } });
}

document.querySelectorAll(".langs button").forEach(function (b) {
    b.addEventListener("click", function () {
        currentLang = b.dataset.lang;
        try { localStorage.setItem("fyp_lang", currentLang); } catch (e) {}
        applyLang();
    });
});

