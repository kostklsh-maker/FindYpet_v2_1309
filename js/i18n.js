function applyLang() {
    const html = document.documentElement;
    html.lang = currentLang;
    html.dir = currentLang === "he" ? "rtl" : "ltr";
    document.title = t("docTitle");
    document.querySelectorAll("[data-t]").forEach(function (el) { el.textContent = t(el.dataset.t); });
    // только наши тексты из I18N (с <b>, <br>) — сообщения бота в демо; пользовательский ввод сюда не попадает
    document.querySelectorAll("[data-t-html]").forEach(function (el) { el.innerHTML = t(el.dataset.tHtml); });
    document.querySelectorAll("[data-t-aria]").forEach(function (el) { el.setAttribute("aria-label", t(el.dataset.tAria)); });
    document.querySelectorAll("[data-t-ph]").forEach(function (el) { el.placeholder = t(el.dataset.tPh); });
    document.querySelectorAll(".langs button").forEach(function (b) {
        b.classList.toggle("on", b.dataset.lang === currentLang);
        b.setAttribute("aria-pressed", b.dataset.lang === currentLang ? "true" : "false");
    });
    if (typeof PRICING !== "undefined") {
        document.querySelectorAll("[data-price]").forEach(function (el) {
            const v = priceOf(el.dataset.price); el.textContent = v ? money(v) : "";
        });
        document.querySelectorAll("[data-price-min]").forEach(function (el) { el.textContent = money(PRICING.tag); });
    }
    langListeners.forEach(function (fn) { try { fn(currentLang); } catch (e) { console.error(e); } });
}

document.querySelectorAll(".langs button").forEach(function (b) {
    b.addEventListener("click", function () {
        currentLang = b.dataset.lang;
        try { localStorage.setItem("fyp_lang", currentLang); } catch (e) {}
        // адрес страницы — как у языковой версии (/, /he/, /ru/), чтобы ссылкой делились на нужном языке
        try {
            if (/^\/(he\/|ru\/)?$/.test(location.pathname)) {
                history.replaceState(null, "", (currentLang === "en" ? "/" : "/" + currentLang + "/") + location.search + location.hash);
            }
        } catch (e) {}
        applyLang();
    });
});

