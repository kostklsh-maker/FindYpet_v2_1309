let currentLang = (function () {
    try { const s = localStorage.getItem("fyp_lang"); if (s && I18N[s]) return s; } catch (e) {}
    const n = (navigator.language || "en").slice(0, 2).toLowerCase();
    return n === "he" || n === "iw" ? "he" : n === "ru" ? "ru" : "en";
})();

function t(key, vars) {
    let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
    if (vars) Object.keys(vars).forEach(function (k) { s = s.split("{" + k + "}").join(vars[k]); });
    return s;
}

// Цены: "79 ₪" → 79; обратно — формат как в PLANS
function planNum(id) {
    const p = typeof PLANS !== "undefined" && PLANS[id];
    return p ? parseFloat(String(p.price).replace(/[^\d.]/g, "")) || 0 : 0;
}
function money(n) {
    const sample = typeof PLANS !== "undefined" && PLANS.smart ? String(PLANS.smart.price) : "0 ₪";
    return sample.replace(/[\d.,]+/, String(Math.round(n)));
}

const langListeners = [];
function onLang(fn) { langListeners.push(fn); }

function applyLang() {
    const html = document.documentElement;
    html.lang = currentLang;
    html.dir = currentLang === "he" ? "rtl" : "ltr";
    document.title = t("docTitle");
    document.querySelectorAll("[data-t]").forEach(function (el) { el.textContent = t(el.dataset.t); });
    document.querySelectorAll("[data-t-ph]").forEach(function (el) { el.placeholder = t(el.dataset.tPh); });
    document.querySelectorAll(".langs button").forEach(function (b) {
        b.classList.toggle("on", b.dataset.lang === currentLang);
        b.setAttribute("aria-pressed", b.dataset.lang === currentLang ? "true" : "false");
    });
    if (typeof PLANS !== "undefined") {
        document.querySelectorAll("[data-price]").forEach(function (el) {
            const p = PLANS[el.dataset.price]; el.textContent = p ? p.price : "";
        });
        const min = Math.min.apply(null, Object.keys(PLANS).map(planNum).filter(Boolean));
        document.querySelectorAll("[data-price-min]").forEach(function (el) { el.textContent = isFinite(min) ? money(min) : ""; });
    }
    langListeners.forEach(function (fn) { try { fn(currentLang); } catch (e) { console.error(e); } });
}

document.querySelectorAll(".langs button").forEach(function (b) {
    b.addEventListener("click", function () {
        currentLang = b.dataset.lang;
        try { localStorage.setItem("fyp_lang", currentLang); } catch (e) {}
        applyLang();
    });
});

applyLang();
